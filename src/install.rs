    /// Every `!`-prefixed shell line interpolating a positional argument must
    /// quote it. Unquoted `$1` with no argument supplied collapses to nothing,
    /// so `--scope $1` reaches clap as a flag missing its value and the command
    /// dies before engram's scope cascade is ever consulted.
    #[test]
    fn shell_lines_quote_positional_arguments() {
        for command in COMMANDS {
            for line in command
                .body
                .lines()
                .filter(|l| l.trim_start().starts_with("!`"))
            {
                for pos in ["$1", "$2", "$ARGUMENTS"] {
                    if line.contains(pos) {
                        assert!(
                            line.contains(&format!("\"{pos}\"")),
                            "{}: unquoted {pos} in shell line: {line}",
                            command.name
                        );
                    }
                }
            }
        }
    }

