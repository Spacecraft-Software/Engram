    #[test]
    fn every_surfaceless_harness_states_its_own_reason() {
        let mut seen: Vec<&str> = Vec::new();
        for spec in harness::ALL {
            if let CommandSurface::None { detail } = spec.command_surface {
                assert!(!detail.is_empty(), "{} has an empty reason", spec.name);
                assert!(
                    !seen.contains(&detail),
                    "{} reuses another harness's reason verbatim",
                    spec.name
                );
                seen.push(detail);
            }
        }
        assert!(!seen.is_empty());
    }

    /// A skill's frontmatter is a different contract from a command file's:
    /// `name` + `description`, no `argument-hint`, no `allowed-tools`. The
    /// description is lifted from the shared template so the two surfaces
    /// cannot describe the same command differently.
    #[test]
    fn skills_carry_gemini_frontmatter_and_the_shared_description() {
        let spec = harness::spec(harness::Harness::Antigravity);
        for command in COMMANDS {
            let out = render_skill(command.name, command.body, spec, "/shared/engram.db");
            assert!(out.starts_with("---\n"), "{}: {out}", command.name);
            assert!(out.contains(&format!("name: engram-{}", command.name)));
            assert!(!out.contains("argument-hint:"), "{}", command.name);
            assert!(!out.contains("allowed-tools:"), "{}", command.name);
            assert!(out.contains("--db /shared/engram.db"));
            assert!(!out.contains("{{DB}}"));

            let description = frontmatter_field(command.body, "description").expect("description");
            assert!(out.contains(&description), "{}", command.name);
            // Standard §5.6: a shipped SKILL.md description is capped at 1000
            // characters. Assert the cap here, where it would first be broken.
            assert!(
                description.chars().count() <= 1000,
                "{}: description is {} chars",
                command.name,
                description.chars().count()
            );
        }
    }
